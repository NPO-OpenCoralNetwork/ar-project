const r2 = (n: number) => +n.toFixed(2)
/** 楕円（ベジェ4本） */
const ellipse = (cx: number, cy: number, rx: number, ry: number) => {
  const [x0, x1, y0, y1] = [cx - rx, cx + rx, cy - ry, cy + ry].map(r2)
  const [kx, ky] = [r2(rx * 0.55), r2(ry * 0.55)]
  return `M${x0},${cy} C${x0},${r2(cy - ky)} ${r2(cx - kx)},${y0} ${cx},${y0} C${r2(cx + kx)},${y0} ${x1},${r2(cy - ky)} ${x1},${cy} C${x1},${r2(cy + ky)} ${r2(cx + kx)},${y1} ${cx},${y1} C${r2(cx - kx)},${y1} ${x0},${r2(cy + ky)} ${x0},${cy} Z`
}

