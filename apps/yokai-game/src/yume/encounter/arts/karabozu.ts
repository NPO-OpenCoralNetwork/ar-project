/** 線の一覧を部品の追加の線にする（flip なら左右を反転。w が 0 なら各線の太さを使う） */
const lines = (ds: (string | [string, number])[], w: number, flip = false): [string, number][] =>
  ds.map((x): [string, number] => {
    const [d, ww] = typeof x === 'string' ? [x, w] : [x[0], w || x[1]]
    return [flip ? mirror(d, 100) : d, ww]
  })

